package dostup

// Rule-based классификация ответов для Шага 3 (автопилот).
//
// Функция SuggestState возвращает статус Alaveteli, если текст ответа
// содержит ЯВНЫЕ маркеры, иначе пустую строку — тогда решение оставляет
// пользователю (или AI, который тоже умеет предлагать только уверенные).
//
// Важно: бот НИКОГДА не классифицирует чужие сомнительные ответы. Только
// явные случаи: «відмовлено», «надаємо», «частково», «не володіє».
// Всё остальное — на кнопки пользователю.

import (
	"strings"
)

// suggestMarkers — пары: статус → маркеры (подстрока, lower-case).
var suggestMarkers = []struct {
	state   string
	markers []string
}{
	{// полная/частичная отказная
		"rejected", []string{
			"відмовлено у наданні", "відмовляємо у наданні", "відмовляємо в наданні",
			"не може бути надана", "не може бути надано", "не підлягає наданню",
			"не підлягає розкриттю", "відмовлено в задоволенні", "відмовляємо",
			"відмовлено", "відмова у наданні", "відмова в наданні",
			"повідомляємо про відмову", "змушені відмовити", "відмовляємося надати",
		},
	},
	{// предоставлено по существу
		"successful", []string{
			"надаємо", "надається", "надаються", "надаємо інформацію", "надано інформацію",
			"у додатку", "в додатку", "у вкладенні", "в вкладенні",
			"додаємо", "надсилаємо", "перелік", "копію", "копія",
			"довідку", "довідка", "виписку", "виписка", "розрахунок",
		},
	},
	{// частично
		"partially_successful", []string{
			"частково", "деяку інформацію", "частину інформації", "частково задоволено",
		},
	},
	{// орган не владеет информацией
		"not_held", []string{
			"не володіє", "не володіємо", "не розпоряджається", "не розпоряджаємося",
			"немає інформації", "немає запитуваної", "не маємо можливості надати",
			"інформація відсутня", "відсутня інформація", "не знаходиться в нашому",
		},
	},
}

// SuggestState — rule-based предложение статуса по тексту ответа.
// Возвращает пустую строку, если ответ не содержит явных маркеров
// (решение должен принять человек — или AI, см. AIState).
func SuggestState(text string) string {
	t := normalizeReplyText(text)
	if t == "" {
		return ""
	}
	for _, sm := range suggestMarkers {
		for _, m := range sm.markers {
			if strings.Contains(t, m) {
				return sm.state
			}
		}
	}
	return ""
}

// AIStateToDostup — маппинг вердикта AI (RefusalAnalysis.Type) в статус
// Alaveteli. Возвращает "" для неоднозначных типов: AI может советовать,
// но ПРИМЕНЯТЬ на портале бот должен только уверенные вердикты.
func AIStateToDostup(aiType string) string {
	switch aiType {
	case "refusal":
		return "rejected"
	case "partial":
		return "partially_successful"
	case "substantive":
		return "successful"
	default: // brushoff, ack, unclear — оставляем человеку
		return ""
	}
}
