// ClassifyReply решает, является ли текст ответом по существу или
// промежуточным авто-подтверждением. Порядок правил:
//  1. пустой текст → ReplyUnknown;
//  2. содержательный маркер (пословно) → ReplySubstantive;
//  3. длинный текст (>= 600 знаков) → ReplySubstantive;
//  4. фраза-подтверждение → ReplyAcknowledgement;
//  5. короткий текст со словом «отриман»/«получен» → ReplyAcknowledgement;
//  6. во всех остальных случаях → ReplySubstantive (лучше ошибиться
//     в сторону уведомления, чем пропустить настоящий ответ).
func ClassifyReply(text string) ReplyKind {
        t := normalizeReplyText(text)
        if t == "" {
                return ReplyUnknown
        }
        for _, m := range substringMarkers {
                if strings.Contains(t, m) {
                        return ReplySubstantive
                }
        }
        padded := " " + t + " "
        for _, m := range substantiveMarkers {
                if strings.Contains(padded, " "+strings.ToLower(m)) {
                        return ReplySubstantive
                }
        }
        if len([]rune(t)) >= 600 {
                return ReplySubstantive
        }
        for _, p := range ackPhrases {
                if strings.Contains(t, p) {
                        return ReplyAcknowledgement
                }
        }
        if len([]rune(t)) <= 140 &&
                (strings.Contains(t, "отриман") || strings.Contains(t, "получен")) {
                return ReplyAcknowledgement
        }
        return ReplySubstantive
}

// KindLabel — человекочитаемая метка классификации (для логов/отчётов).
func KindLabel(k ReplyKind) string {
        switch k {
        case ReplyAcknowledgement:
                return "проміжна відповідь (авто-підтвердження)"
        case ReplySubstantive:
                return "відповідь по суті"
        default:
                return "невизначено"
        }
}

// normalizeReplyText приводит текст к нижнему регистру, заменяет
// типографские кавычки/тире и схлопывает пробелы.
func normalizeReplyText(s string) string {
        s = strings.ToLower(s)
        s = strings.NewReplacer(
                "’", "'", "‘", "'", "«", " ", "»", " ",
                "—", " ", "–", " ", "   ", " ",
        ).Replace(s)
        var b strings.Builder
        lastSpace := false
        for _, r := range s {
                if unicode.IsSpace(r) {
                        if !lastSpace {
                                b.WriteRune(' ')
                        }
                        lastSpace = true
                        continue
                }
                lastSpace = false
                b.WriteRune(r)
        }
        return strings.TrimSpace(b.String())
}
