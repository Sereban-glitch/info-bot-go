// ReplyKind — классификация входящего сообщения органа.
type ReplyKind int

const (
        // ReplyUnknown — текста нет, классифицировать невозможно.
        ReplyUnknown ReplyKind = iota
        // ReplySubstantive — ответ по существу запроса (то, что ждёт пользователь).
        ReplySubstantive
        // ReplyAcknowledgement — промежуточное подтверждение получения
        // («ваш лист отримано», «зареєстровано, буде розглянуто» и т.п.).
        // Ответом по существу НЕ считается: запрос остаётся в ожидании,
        // счётчик ответов не инкрементируется.
        ReplyAcknowledgement
)

