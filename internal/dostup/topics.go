// Topics возвращает список тем в порядке приоритета.
func Topics() []Topic {
	out := make([]Topic, len(topics))
	copy(out, topics)
	return out
}

// TopicByID ищет тему по идентификатору; неизвестный ID → «Інше».
func TopicByID(id string) Topic {
	for _, t := range topics {
		if t.ID == id {
			return t
		}
	}
	return Topic{ID: "other", Emoji: "❓", Title: "Інше"}
}

// ClassifyTopic определяет тему запроса по тексту (тема + орган).
// Текст нормализуется: нижний регистр, типографские кавычки и тире
// заменяются на пробелы (тот же принцип, что в normalizeReplyText),
// пробелы схлопываются. Матчинг — подстрокой по стемам; первая тема
// в порядке приоритета, чей стем найден, выигрывает. Ничего не нашлось —
// «Інше».
func ClassifyTopic(text string) Topic {
	t := normalizeTopicText(text)
	if t == "" {
		return TopicByID("other")
	}
	padded := " " + t + " "
	for _, topic := range topics {
		if topic.ID == "other" {
			continue
		}
		for _, kw := range topicKeywords[topic.ID] {
			// Стемы со встроенными пробелами («база даних», « зсу»,
			// «контакт») матчатся по подстроке нормализованного текста;
			// односложные короткие стемы — тоже по подстроке padded,
			// чтобы уважать границы слов там, где это важно.
			if strings.Contains(padded, kw) {
				return topic
			}
		}
	}
	return TopicByID("other")
}

// normalizeTopicText — lowercase + замена типографики + схлопывание пробелов.
func normalizeTopicText(s string) string {
	s = strings.ToLower(s)
	s = strings.NewReplacer(
		"’", "'", "‘", "'", "«", " ", "»", " ",
		"—", " ", "–", " ", "   ", " ",
	).Replace(s)
	var b strings.Builder
	lastSpace := false
	for _, r := range s {
		if r == ' ' || r == '\t' || r == '\n' || r == '\r' {
			if !lastSpace {
				b.WriteRune(' ')
			}
			lastSpace = true
			continue
		}
		lastSpace = false
		b.WriteRune(r)
	}
	return strings.TrimSpace(b.String())
}
