package moderation

import (
	"strings"
)

// Антиспровокаційний скринінг запитів (ТЗ №10).
//
// Контекст (30–31.08.2026): новий користувач за 6 хвилин після реєстрації
// відправив через спільний акаунт порталу запит про військову посаду
// Буданова К.О., підписавшись «Шварцнегер Арнольд Іванович», адреса
// «Штат Флорида». Прямої загрози немає, але скарга на такий запит може
// заблокувати СПІЛЬНИЙ акаунт порталу — єдиний канал, через який
// працюють усі користувачі. Для правозахисного проєкту на стадії
// зародження це класичний вектор компрометації.
//
// Мета скринінгу — НЕ цензура: запити не забороняються. Чутливі
// (воєнний час / розвідка / приватність третіх осіб) поставлюються
// на коротку перевірку власником: ✅ надіслати через спільний акаунт
// або ❌ відхилити (користувач отримує готовий текст листа для
// самостійної подачі від свого імені — право на запит зберігається).
// Усі інші запити йдуть як завжди, а власник отримує коротке
// повідомлення про КОЖНУ відправку — повна видимість у реальному часі.

// Verdict — результат скринінгу запиту.
type Verdict struct {
	// Hold = true → запит НЕ надсилається автоматично, а чекає рішення
	// власника (черга mod_ok/mod_no). false → звичайна відправка.
	Hold bool
	// Reasons — людські пояснення, чому запит чутливий (для картки
	// власнику). Заповнюється тільки при Hold=true.
	Reasons []string
}

// Rule — правило скринінгу: ALL-семантика (усі стеми мають бути
// присутні в нормалізованому тексті), щоб зменшити хибні спрацювання.
type Rule struct {
	Stems  []string
	Reason string
}

// rules — правила чутливих тем. Стеми в нижньому регістрі, без закінчень.
// Хибні спрацювання дешеві (власник тисне ✅), пропуск — дорогий
// (провокація на спільному акаунті), тому списку дана ширина:
//   - розвідка/спецслужби та їх керівництво (воєнний час);
//   - військова посада/звання конкретних осіб;
//   - державна/воєнна таємниця, грифовані документи;
//   - озброєння, боєприпаси, дислокація та адреси військових частин;
//   - персональні дані третіх осіб (адреса проживання, телефони,
//     стан здоров'я посадовців) — приватність.
//
// Окремо про НЕ-правила: «мобілізація», «ТЦК», «військова частина»
// самі по собі НЕ тримають запит — питання про мобілізаційне
// законодавство і vets-довідки легітимні й часті. Адреса/дислокація
// військових — тримають.
var rules = []Rule{
	{Stems: []string{"буданов"}, Reason: "стосується керівника військової розвідки (Буданов) — воєнний час"},
	{Stems: []string{"залужн"}, Reason: "стосується військового керівництва (Залужний) — воєнний час"},
	{Stems: []string{"сирськ"}, Reason: "стосується військового керівництва (Сирський) — воєнний час"},
	{Stems: []string{"військов", "посад"}, Reason: "військова посада посадової особи (може бути обмежена у воєнний час)"},
	{Stems: []string{"військов", "званн"}, Reason: "військове звання (може бути обмежене у воєнний час)"},
	{Stems: []string{"розвідк"}, Reason: "військова розвідка"},
	{Stems: []string{"спецслужб"}, Reason: "спецслужби"},
	{Stems: []string{"служб", "безпек"}, Reason: "СБУ"},
	{Stems: []string{" сбу"}, Reason: "СБУ"},
	{Stems: []string{"головне управління розвідки"}, Reason: "ГУР (військова розвідка)"},
	{Stems: []string{"державна таємниц"}, Reason: "державна таємниця"},
	{Stems: []string{"воєнна таємниц"}, Reason: "воєнна таємниця"},
	{Stems: []string{"секретн"}, Reason: "секретна/грифована інформація"},
	{Stems: []string{"озброєнн"}, Reason: "озброєння"},
	{Stems: []string{"боєприпас"}, Reason: "боєприпаси"},
	{Stems: []string{"дислокац"}, Reason: "дислокація військових частин"},
	{Stems: []string{"військов", "адрес"}, Reason: "адреса військової частини/об'єкта"},
	{Stems: []string{"адрес", "проживанн"}, Reason: "адреса проживання третьої особи (приватність)"},
	{Stems: []string{"місце проживання"}, Reason: "місце проживання особи (приватність)"},
	{Stems: []string{"домашн", "адрес"}, Reason: "домашня адреса особи (приватність)"},
	{Stems: []string{"телефон", "посадов"}, Reason: "особистий телефон посадової особи (приватність)"},
	{Stems: []string{"стан здоров'я", "посадов"}, Reason: "стан здоров'я посадової особи (приватність)"},
	{Stems: []string{"дата народження", "посадов"}, Reason: "дата народження посадової особи (приватність)"},
}

// Check аналізує запит (тема + текст листа + орган) і вирішує,
// чи ставити його на перевірку власником. Чиста функція.
func Check(subject, body, recipient string) Verdict {
	text := normalize(subject + " " + body + " " + recipient)
	if text == "" {
		return Verdict{}
	}
	padded := " " + text + " "

	seen := map[string]bool{}
	var reasons []string
	for _, r := range rules {
		if allStemsPresent(padded, r.Stems) && !seen[r.Reason] {
			seen[r.Reason] = true
			reasons = append(reasons, r.Reason)
		}
	}
	if len(reasons) == 0 {
		return Verdict{}
	}
	return Verdict{Hold: true, Reasons: reasons}
}

// allStemsPresent — усі стеми правила знайдені в тексті (AND-семантика).
func allStemsPresent(padded string, stems []string) bool {
	for _, s := range stems {
		if !strings.Contains(padded, s) {
			return false
		}
	}
	return len(stems) > 0
}

// normalize — нижній регістр + типографіка → пробіли + схлопнуті
// пробіли (той самий принцип, що й у ClassifyTopic: нормалізація
// не має залежати від кавичок/тире, якими написано запит).
func normalize(s string) string {
	s = strings.ToLower(s)
	s = strings.NewReplacer(
		"’", "'", "‘", "'", "«", " ", "»", " ",
		"—", " ", "–", " ", "   ", " ",
	).Replace(s)
	var b strings.Builder
	lastSpace := false
	for _, r := range s {
		if r == ' ' || r == '\t' || r == '\n' || r == '\r' {
			if !lastSpace {
				b.WriteRune(' ')
			}
			lastSpace = true
			continue
		}
		lastSpace = false
		b.WriteRune(r)
	}
	return strings.TrimSpace(b.String())
}
