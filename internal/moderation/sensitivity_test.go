// Реальний запит 30.08.2026 (тригер ТЗ №10): Офіс Президента,
// військова посада Буданова К.О., підпис «Шварцнегер Арнольд Іванович».
func TestCheckBudanovRealCase(t *testing.T) {
	subject := "Запит про надання інформації щодо військової посади Буданова К.О."
	body := "На підставі статей 1, 13, 19, 20 Закону України «Про доступ до публічної інформації» прошу надати інформацію щодо військової посади Буданова К.О.\n\nЗ повагою,\nШварцнегер Арнольд Іванович"
	v := Check(subject, body, "Офіс Президента України")
	if !v.Hold {
		t.Fatalf("реальний запит Буданова має бути на перевірці, got %+v", v)
	}
	// Хоча б дві ознаки: прізвище + військова посада
	if len(v.Reasons) < 2 {
		t.Errorf("очікувалось ≥2 ознаки, got %v", v.Reasons)
	}
	joined := strings.Join(v.Reasons, "; ")
	if !strings.Contains(joined, "Буданов") {
		t.Errorf("немає ознаки про Буданова: %v", v.Reasons)
	}
}

// Регрес-захист: два інші реальні запити продакшну мають проходити
// без перевірки (МОЗ — статистика хвороб, ДСА — перелік адрес судів).
func TestCheckLegitProdRequests(t *testing.T) {
	cases := []struct {
		name  string
		subj  string
		body  string
		organ string
	}{
		{
			"МОЗ: статистика серцево-судинних",
			"Про надання статистичної інформації щодо серцево-судинних захворювань за перше півріччя 2026 року",
			"Прошу надати статистичну інформацію щодо захворюваності на серцево-судинні захворювання.",
			"Міністерство охорони здоров'я",
		},
		{
			"ДСА: перелік електронних адрес судів",
			"Перелік електронних адрес судів для звернень громадян",
			"Прошу надати перелік електронних адрес судів для надсилання звернень громадян.",
			"Державна судова адміністрація України",
		},
		{
			"типовий запит: ремонт доріг",
			"Витрати на ремонт доріг у 2025 році",
			"Прошу надати інформацію про витрати місцевого бюджету на ремонт доріг.",
			"Запорізька міська рада",
		},
	}
	for _, tc := range cases {
		if v := Check(tc.subj, tc.body, tc.organ); v.Hold {
			t.Errorf("%s: легітимний запит не має ставитись на перевірку, reasons=%v", tc.name, v.Reasons)
		}
	}
}

// Хибні спрацювання, які ловили б прості правила:
// «гуртожиток» не містить ГУР, мобілізаційне право — легітимна тема,
// «президент» сам по собі — ні (запити до ОП бувають звичайними).
func TestCheckFalsePositives(t *testing.T) {
	cases := []struct {
		name  string
		subj  string
		body  string
		organ string
	}{
		{"гуртожиток ≠ ГУР", "Розподіл місць у гуртожитку", "Прошу надати інформацію про правила розподілу місць у студентському гуртожитку.", "Міністерство освіти і науки"},
		{"мобілізаційне право", "Порядок бронювання від мобілізації", "Прошу роз'яснити порядок бронювання працівників від мобілізації.", "Міністерство економіки"},
		{"зарплатня вчителів", "Зарплата вчителів у 2026 році", "Прошу надати інформацію про середню зарплату вчителів.", "Управління освіти"},
		{"статистика судів", "Статистика розгляду справ судами", "Прошу надати статистику кількості справ, розглянутих судами за 2025 рік.", " "},
		{"соціальні виплати", "Виплати внутрішньо переміщеним особам", "Прошу надати інформацію про розмір виплат ВПО.", "Міністерство соціальної політики"},
	}
	for _, tc := range cases {
		if v := Check(tc.subj, tc.body, tc.organ); v.Hold {
			t.Errorf("%s: хибне спрацювання, reasons=%v", tc.name, v.Reasons)
		}
	}
}

func TestCheckSensitive(t *testing.T) {
	cases := []struct {
		name   string
		subj   string
		body   string
		organ  string
		wantIn string // фрагмент очікуваної причини
	}{
		{"військова розвідка", "Діяльність військової розвідки", "Прошу надати інформацію про структуру.", "", "розвід"},
		{"СБУ повна назва", "Запит до Служби безпеки України", "статистика звернень", "", "СБУ"},
		{"СБУ абревіатура", "Статистика", "прошу дані про звернення до СБУ за 2025 рік", "", "СБУ"},
		{"держтаємниця", "Список документів", "Прошу надати перелік документів із грифом «державна таємниця»", "", "таємниц"},
		{"озброєння", "Обсяг озброєння", "Прошу надати інформацію про кількість.", "", "озброєнн"},
		{"дислокація", "Дислокація", "Прошу надати перелік дислокацій військових частин", "", "дислокац"},
		{"адреса військової частини", "Адреса", "Прошу надати адресу військової частини А-1234", "", "військов"},
		{"адреса проживання особи", "Адреса", "Прошу надати адресу проживання громадянина П.", "", "приватн"},
		{"домашня адреса", "Контакти", "Прошу повідомити домашню адресу посадової особи", "", "адрес"},
		{"секретні документи", "Перелік", "Прошу надати перелік секретних наказів", "", "секретн"},
		{"військове звання", "Звання", "Прошу повідомити військове звання посадової особи", "", "званн"},
	}
	for _, tc := range cases {
		v := Check(tc.subj, tc.body, tc.organ)
		if !v.Hold {
			t.Errorf("%s: очікував Hold=true, got false", tc.name)
			continue
		}
		if tc.wantIn != "" && !strings.Contains(strings.Join(v.Reasons, "; "), tc.wantIn) {
			t.Errorf("%s: ознака %q не знайдена у %v", tc.name, tc.wantIn, v.Reasons)
		}
	}
}

// Нормалізація: кейс, типографські кавички і тире не ламають матчинг.
func TestCheckNormalization(t *testing.T) {
	if v := Check("ВІЙСЬКОВУ ПОСАДУ БУДАНОВА", "", ""); !v.Hold {
		t.Error("великі літери мають матчитись")
	}
	if v := Check("«військова розвідка»", "", ""); !v.Hold {
		t.Error("типографські кавички не мають заважати")
	}
	if v := Check("", "", ""); v.Hold {
		t.Error("порожній запит — не чутливий")
	}
}

// Дублікати ознак не дублюються у списку причин.
func TestCheckNoDuplicateReasons(t *testing.T) {
	v := Check("військова посада Буданова", "Буданов і знову буданов, військова посада", "")
	if !v.Hold {
		t.Fatal("має Hold")
	}
	seen := map[string]int{}
	for _, r := range v.Reasons {
		seen[r]++
	}
	for r, n := range seen {
		if n > 1 {
			t.Errorf("причина %q повторюється %d разів", r, n)
		}
	}
}
