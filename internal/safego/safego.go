// Package safego — страховка для фоновых задач (ТЗ №4, D3).
//
// Проблема: если фоновая горутина паникует, процесс падает целиком —
// вместе с ботом. Стек паники при этом теряется в общем потоке лога,
// а systemd молча перезапускает сервис.
//
// Решение: safego.Go запускает задачу так, что паника ловится, пишется
// в журнал с пометкой [PANIC] и стеком вызовов — а цикл (тикер) живёт
// дальше: следующий тик начнётся с чистого состояния.
package safego

import (
	"log"
	"runtime/debug"
)

// defaultLogf — стандартный журнал; logf переключается в тестах,
// чтобы проверять, что паника действительно записывается, а не
// пропадает молча.
var defaultLogf = log.Printf
var logf = defaultLogf

// Go запускает fn в новой горутине с восстановлением после паники.
// name — человекочитаемое имя задачи для журнала.
func Go(name string, fn func()) {
	go run(name, fn)
}

// Run выполняет fn синхронно, но с восстановлением после паники.
// Используется для тела одной итерации цикла: паника итерации не
// убивает цикл.
func Run(name string, fn func()) {
	run(name, fn)
}

func run(name string, fn func()) {
	defer func() {
		if r := recover(); r != nil {
			logf("[PANIC] %s: %v\n%s", name, r, debug.Stack())
		}
	}()
	fn()
}
